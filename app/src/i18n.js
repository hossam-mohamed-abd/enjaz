let currentLanguage = "en";
const englishHTML = new Map();
const englishPlaceholders = new Map();

function captureEnglishContent() {
  if (englishHTML.size) return;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    englishHTML.set(element, element.innerHTML);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    englishPlaceholders.set(element, element.getAttribute("placeholder") || "");
  });
}

export function getLanguage() {
  return currentLanguage;
}

export function t(key) {
  return runtimeCopy[currentLanguage]?.[key] ?? runtimeCopy.en[key] ?? key;
}

export function setLanguage(language, { notify = false } = {}) {
  if (!['en', 'ar'].includes(language)) return;
  captureEnglishContent();
  currentLanguage = language;
  const isArabic = language === "ar";

  document.documentElement.lang = language;
  document.documentElement.dir = isArabic ? "rtl" : "ltr";
  document.title = isArabic
    ? "إنجاز وورلد — تركيا، على مقاسك"
    : "Enjaz World — Türkiye, designed around you";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (isArabic) {
      if (arabic[key]) element.textContent = arabic[key];
    } else {
      element.innerHTML = englishHTML.get(element) ?? element.innerHTML;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    element.setAttribute(
      "placeholder",
      isArabic ? placeholders[key] || englishPlaceholders.get(element) : englishPlaceholders.get(element)
    );
  });

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.language === language);
    button.setAttribute("aria-pressed", String(button.dataset.language === language));
  });
  const current = document.getElementById("current-language");
  if (current) current.textContent = language.toUpperCase();

  try { localStorage.setItem("enjaz-language", language); } catch { /* Storage is optional. */ }
  document.dispatchEvent(new CustomEvent("enjaz:language", { detail: { language, notify } }));
}

export function initLanguage() {
  captureEnglishContent();
  let saved = "en";
  try { saved = localStorage.getItem("enjaz-language") || "en"; } catch { /* Use English. */ }
  setLanguage(saved === "ar" ? "ar" : "en");
}
