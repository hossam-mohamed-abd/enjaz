import { build } from "esbuild";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const imagesDirectory = join(projectRoot, "public", "images");
const templatePath = join(projectRoot, "app", "index.html");
const outputPath = join(projectRoot, "index.html");
const distDirectory = join(projectRoot, "dist");

const mimeTypes = {
  ".webp": "image/webp",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".svg": "image/svg+xml"
};

function dataUri(buffer, mimeType) {
  return `data:${mimeType};base64,${buffer.toString("base64")}`;
}

const result = await build({
  entryPoints: [join(projectRoot, "app", "src", "main.js")],
  outfile: join(projectRoot, ".standalone", "enjaz.js"),
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2022",
  charset: "utf8",
  minify: true,
  legalComments: "inline",
  loader: {
    ".woff": "dataurl",
    ".woff2": "dataurl"
  }
});

const javascriptOutput = result.outputFiles.find((file) => file.path.endsWith(".js"));
const cssOutput = result.outputFiles.find((file) => file.path.endsWith(".css"));

if (!javascriptOutput || !cssOutput) {
  throw new Error("The standalone JavaScript or CSS bundle was not generated.");
}

let javascript = javascriptOutput.text
  // Minified bundles retain whitespace inside GLSL/HTML template literals.
  // Trimming only line edges keeps the generated HTML Git-diff clean.
  .replace(/^[ \t]+/gm, "")
  .replace(/[ \t]+$/gm, "");
const css = cssOutput.text;
let html = await readFile(templatePath, "utf8");

const imageFiles = (await readdir(imagesDirectory)).filter((file) => mimeTypes[extname(file)]);
for (const file of imageFiles) {
  const image = await readFile(join(imagesDirectory, file));
  const uri = dataUri(image, mimeTypes[extname(file)]);
  const sourcePath = `./images/${file}`;
  html = html.split(sourcePath).join(uri);
  javascript = javascript.split(sourcePath).join(uri);
}

html = html.replace("<!-- ENJAZ_STYLES -->", () => `<style>\n${css}\n</style>`);
html = html.replace(
  '<script type="module" src="./src/main.js"></script>',
  () => `<script>\n${javascript.replace(/<\/script/gi, "<\\/script")}\n</script>`
);
html = html.replace(
  "<!doctype html>",
  "<!doctype html>\n<!-- Self-contained offline build: open this file directly. Generated by npm run build. -->"
);

const unresolvedPaths = [
  "<!-- ENJAZ_STYLES -->",
  'src="./src/main.js"',
  'src="./images/',
  'href="./images/'
].filter((path) => html.includes(path));
if (unresolvedPaths.length) {
  throw new Error(`Unresolved standalone assets: ${unresolvedPaths.join(", ")}`);
}
if (/<script\b[^>]*\bsrc\s*=/i.test(html) || /<link\b[^>]*\brel="stylesheet"/i.test(html)) {
  throw new Error("The standalone HTML still contains an external script or stylesheet.");
}

await mkdir(distDirectory, { recursive: true });
await Promise.all([
  writeFile(outputPath, html),
  writeFile(join(distDirectory, "index.html"), html),
  writeFile(join(distDirectory, ".nojekyll"), "")
]);

const sizeInMiB = (Buffer.byteLength(html) / 1024 / 1024).toFixed(2);
console.log(`Standalone website generated: index.html (${sizeInMiB} MiB)`);
console.log("Open index.html directly — no server, installation, or internet connection is required for the UI.");
console.log("A matching GitHub Actions artifact was generated in dist/.");
